// Writes src/lib/api-types.ts from the API's spec (../docs/api.schema.json, which loom
// generates from its Rust types): each resource's item and each command's params as
// TypeScript. Run: bun scripts/api-types.ts (the build runs it).
import { readFileSync, writeFileSync } from "node:fs";

type Schema = { type?: string | string[]; description?: string; properties?: Record<string, Schema>; required?: string[]; items?: Schema; enum?: unknown[]; oneOf?: Schema[]; anyOf?: Schema[] };
const spec = JSON.parse(readFileSync(new URL("../../docs/api.schema.json", import.meta.url), "utf8"));

function ts(s: Schema | undefined, indent = ""): string {
  if (!s) return "unknown";
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  const alts = s.oneOf ?? s.anyOf;
  if (alts) return alts.map((a) => ts(a, indent)).join(" | ");
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (types.length > 1) return types.map((t) => ts({ ...s, type: t }, indent)).join(" | ");
  switch (types[0]) {
    case "string": return "string";
    case "boolean": return "boolean";
    case "integer": case "number": return "number";
    case "null": return "null";
    case "array": return `${s.items ? wrap(ts(s.items, indent)) : "unknown"}[]`;
    case "object": return s.properties ? object(s, indent) : "Record<string, unknown>";
    default: return "unknown";
  }
}
const wrap = (t: string) => (t.includes("|") ? `(${t})` : t);
function object(s: Schema, indent: string): string {
  const req = new Set(s.required ?? []);
  const lines = Object.entries(s.properties ?? {}).map(([k, v]) => {
    const doc = v.description ? `${indent}  /** ${v.description.replace(/\*\//g, "* /")} */\n` : "";
    return `${doc}${indent}  ${/^[a-z_][a-z0-9_]*$/i.test(k) ? k : JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(v, indent + "  ")};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}
const pascal = (name: string) => name.split(/[^a-z0-9]+/i).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const doc = (d?: string) => (d ? `/** ${d.replace(/\*\//g, "* /")} */\n` : "");

let out = `// Generated by scripts/api-types.ts from docs/api.schema.json: don't edit by hand.\n\nexport const PROTOCOL = ${JSON.stringify(spec.protocol)};\n\n`;
const res: [string, string][] = [];
for (const [name, r] of Object.entries<any>(spec.resources)) {
  const t = pascal(name.replace(/<[^>]+>/g, "")) + "Item";
  out += `${doc(r.description)}export type ${t} = ${ts(r.item)};\n\n`;
  res.push([name, t]);
}
out += `/** Every resource's name and the type of its items. */\nexport interface Resources {\n${res.map(([n, t]) => `  ${JSON.stringify(n)}: ${t};`).join("\n")}\n}\n\n`;
const cmd: [string, string][] = [];
for (const [name, c] of Object.entries<any>(spec.commands)) {
  const t = pascal(name) + "Params";
  out += `${doc(c.description + (c.result ? ` Result: ${c.result}` : ""))}export type ${t} = ${c.params ? ts(c.params) : "Record<string, never>"};\n\n`;
  cmd.push([name, t]);
}
out += `/** Every command's name and the type of its params. */\nexport interface Commands {\n${cmd.map(([n, t]) => `  ${JSON.stringify(n)}: ${t};`).join("\n")}\n}\n`;
writeFileSync(new URL("../src/lib/api-types.ts", import.meta.url), out);
console.log(`api-types: ${res.length} resources, ${cmd.length} commands`);
